"""Collect permissively licensed Python for the from-scratch 1B corpus.

    python -I experiments/build_code_clean.py --out data/code_clean --target-gb 3.4

Source: codeparrot/github-code-clean (https://huggingface.co/datasets/codeparrot/github-code-clean),
GitHub files with each repository's detected licence in a `license` column. Only
these licences are kept, all of which allow any use including commercial, with
attribution: MIT, Apache-2.0, BSD-2-Clause, BSD-3-Clause, ISC, CC0-1.0, Unlicense.
GPL, AGPL, LGPL, MPL, EPL and Artistic files are dropped (docs/PLAN_1B.md, "Data").

This replaces base v2's Python (codeparrot-clean with GPL/AGPL files mixed in,
OpenCodeInstruct's model-generated answers, OPC's ChatGPT-derived text), so the
new base has no copyleft and no model-generated code.

Filters, after StarCoder's (Li et al. 2023, section 3): file under 100 kB, average
line under 100 characters and longest under 1,000, at least 25% alphanumeric
characters, no "auto-generated" / "do not edit" marker in the first 500
characters, and exact duplicates removed (hash of the whitespace-stripped text).

Output: parquet shards with text, repo_name, path, license, written as they
fill, so attribution (repo and licence for every file) travels with the data.
Shards are read remotely, column by column; nothing from the dataset is executed.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import time
from collections import deque
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

PERMISSIVE = {"mit", "apache-2.0", "bsd-2-clause", "bsd-3-clause", "isc", "cc0-1.0", "unlicense"}
REPO = "datasets/codeparrot/github-code-clean/data"
N_SHARDS = 880
MARKERS = ("auto-generated", "autogenerated", "automatically generated", "do not edit", "generated by")


def keep(code: str) -> bool:
    if not code or len(code) > 100_000:
        return False
    lines = code.splitlines() or [""]
    if max(map(len, lines)) > 1000 or len(code) / len(lines) > 100:
        return False
    if sum(c.isalnum() for c in code) < 0.25 * len(code):
        return False
    head = code[:500].lower()
    return not any(m in head for m in MARKERS)


def read_shard(i: int):
    import pyarrow as pa
    import pyarrow.compute as pc
    import pyarrow.parquet as pq
    from huggingface_hub import HfFileSystem
    path = f"{REPO}/train-{i:05d}-of-{N_SHARDS:05d}.parquet"
    for attempt in range(4):
        try:
            with HfFileSystem().open(path, "rb", block_size=8 << 20) as f:
                pf = pq.ParquetFile(f)
                out = []
                for rg in range(pf.num_row_groups):
                    meta = pf.read_row_group(rg, columns=["language", "license"])
                    mask = pc.and_(pc.equal(meta["language"], "Python"),
                                   pc.is_in(meta["license"], value_set=pa.array(sorted(PERMISSIVE))))
                    if not pc.any(mask).as_py():
                        continue
                    t = pf.read_row_group(rg, columns=["code", "repo_name", "path", "license"]).filter(mask)
                    out.extend(t.to_pylist())
                return i, out
        except Exception as e:                       # network hiccups: retry, then give up on this shard
            err = e
            time.sleep(10 * (attempt + 1))
    return i, err


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default="data/code_clean")
    ap.add_argument("--target-gb", type=float, default=3.4, help="stop after this much kept text")
    ap.add_argument("--workers", type=int, default=4)
    ap.add_argument("--rows-per-file", type=int, default=50_000)
    a = ap.parse_args()
    import pyarrow as pa
    import pyarrow.parquet as pq
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    state_path = out / "progress.json"
    st = json.loads(state_path.read_text()) if state_path.exists() else \
        {"shards_done": [], "files": 0, "bytes": 0, "parts": 0, "dropped": {}, "failed": []}
    seen = set()
    for f in sorted(out.glob("part-*.parquet")):           # resume: rebuild the dedupe set
        for t in pq.read_table(f, columns=["text"]).column("text").to_pylist():
            seen.add(hashlib.sha1("".join(t.split()).encode()).digest())
    buf, t0 = [], time.time()

    def flush():
        nonlocal buf
        if buf:
            pq.write_table(pa.Table.from_pylist(buf), out / f"part-{st['parts']:04d}.parquet", compression="zstd")
            st["parts"] += 1
            buf = []
        state_path.write_text(json.dumps(st, indent=1))

    todo = [i for i in range(N_SHARDS) if i not in st["shards_done"]]
    def results():
        """Shard results in order, with at most 2 x workers downloads in flight,
        so stopping at the target does not wait for every remaining shard."""
        with ThreadPoolExecutor(a.workers) as pool:
            queue, it = deque(), iter(todo)
            for i in it:
                queue.append(pool.submit(read_shard, i))
                if len(queue) >= 2 * a.workers:
                    break
            while queue:
                yield queue.popleft().result()
                nxt = next(it, None)
                if nxt is not None:
                    queue.append(pool.submit(read_shard, nxt))

    gen = results()
    try:
        for i, rows in gen:
            if isinstance(rows, Exception):
                st["failed"].append(i)
                print(f"shard {i}: failed ({type(rows).__name__}: {str(rows)[:80]})", flush=True)
                continue
            for r in rows:
                code = r["code"]
                if not keep(code):
                    st["dropped"]["filter"] = st["dropped"].get("filter", 0) + 1
                    continue
                h = hashlib.sha1("".join(code.split()).encode()).digest()
                if h in seen:
                    st["dropped"]["duplicate"] = st["dropped"].get("duplicate", 0) + 1
                    continue
                seen.add(h)
                buf.append({"text": code, "repo_name": r["repo_name"], "path": r["path"], "license": r["license"]})
                st["files"] += 1
                st["bytes"] += len(code.encode("utf-8"))
                if len(buf) >= a.rows_per_file:
                    flush()
            st["shards_done"].append(i)
            print(f"shard {i}: {st['files']:,} files, {st['bytes'] / 1e9:.2f} GB kept, "
                  f"{time.time() - t0:.0f}s", flush=True)
            if st["bytes"] >= a.target_gb * 1e9:
                break
    finally:
        gen.close()    # waits for at most 2 x workers downloads already in flight
    flush()
    print(f"done: {st['files']:,} files, {st['bytes'] / 1e9:.2f} GB, dropped {st['dropped']}, "
          f"failed shards {st['failed']}", flush=True)


if __name__ == "__main__":
    main()
