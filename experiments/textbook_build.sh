#!/bin/bash
# RESULTS.md 31, phase 1: the textbook-heavy coder corpus. CPU, ~1 h after
# the downloads.
#
# The coder in section 25 reached 4.9% HumanEval on a corpus that is 53% raw
# GitHub Python and 7% exercises. phi-1-small reached ~45% at a similar size
# on 7B tokens of textbook-quality Python, and docs/CODER_PLAN.md said so at
# the time. This inverts the ratio to find out how much of that gap is the
# data rather than the model.
#
# Held fixed from section 25 so only the Python composition changes: the
# English share (fineweb-edu), the Hindi share, the code32k tokenizer, the
# model, and the 250,000-step probe budget.
#
# python-edu, the obvious source, ships only Software Heritage blob ids --
# 3.8M per-file fetches, no text -- so the synthetic side comes from datasets
# that ship text: jinaai/code_exercises, nvidia/OpenCodeInstruct and
# OpenCoder-LLM/opc-sft-stage1.
#
# EVERY source is decontaminated against MBPP and HumanEval by 13-gram
# overlap before it enters the corpus -- the synthetic ones while they are
# converted, the text ones in their own pass below. The synthetic sets are
# generated by models that have seen those benchmarks, and the filter earns
# its place:
#
#   code_exercises     4,028 documents dropped
#   OpenCodeInstruct  13,562
#   opc-sft-stage1    14,378
#
# -- prime checks, roman numerals and list sorting, near verbatim. Section
# 25's corpus and tuning set had no such filter, and tools_contamination.py
# measured the consequence after the fact: 18 of the 257 MBPP problems it
# reports pass@1 on had their reference solution or tests in the tuning
# data. Training on that and then quoting pass@1 measures memorisation,
# which is the criticism phi-1 attracted.
export PATH="/usr/bin:/bin:$PATH"   # before dirname: a detached Git Bash has no MSYS tools
cd "$(dirname "$0")/.." || exit 1
export PYTHONIOENCODING=utf-8
set -e

RAW=data/raw
echo "=== TEXTBOOK SOURCES ($(date +%H:%M)) ==="

# phi-1's open analogue: problem statement plus complete solution.
[ -s data/tb_exercises.txt ] || python -u convert_parquet.py textbook \
    --in "$RAW/jinaai__code_exercises/data/*.parquet" \
    --q-col problem --a-col solution --decontaminate \
    --out data/tb_exercises.txt

# Instruction/output pairs, reduced to their Python block. This one ships the
# result of running ten unit tests against every solution: 48% pass all ten,
# 13% fail all ten. Keeping only the verified ones halves the yield and is the
# closest thing in an open dataset to what "textbook quality" is supposed to
# mean, so it is worth the shards.
[ -s data/tb_opencode.txt ] || python -u convert_parquet.py textbook \
    --in "$RAW/nvidia__OpenCodeInstruct/data/*.parquet" \
    --q-col input --a-col output --python-only --decontaminate \
    --score-col average_test_score --min-pair-score 1.0 \
    --out data/tb_opencode.txt

[ -s data/tb_opc.txt ] || python -u convert_parquet.py textbook \
    --in "$RAW/OpenCoder-LLM__opc-sft-stage1/data/*.parquet" \
    --q-col instruction --a-col output --python-only --decontaminate \
    --out data/tb_opc.txt

echo "=== ENGLISH ($(date +%H:%M)) ==="
[ -s data/english_edu2.txt ] || python -u convert_parquet.py fineweb \
    --in "$RAW/HuggingFaceFW__fineweb-edu/sample/10BT/*.parquet" \
    --out data/english_edu2.txt --mb 1700

echo "=== DECONTAMINATE THE TEXT SOURCES ($(date +%H:%M)) ==="
# The three sources above arrive as parquet and are filtered while they are
# converted. These three arrive as text from fetch_code.py and
# fetch_hindi.py, so they need the same filter applied afterwards -- and raw
# GitHub is the likeliest place of all to be holding a benchmark answer,
# because MBPP and HumanEval problems are themselves public repositories.
# Measured before filtering: gh_python.txt alone carried the reference
# answer to 4 of MBPP's 257 problems and 5 of HumanEval's 164.
for f in gh_python english_edu2 hindi_tb; do
  [ -s "data/$f.clean.txt" ] || python -u convert_parquet.py clean \
      --in "data/$f.txt" --out "data/$f.clean.txt"
done

echo "=== MIX ($(date +%H:%M)) ==="
# Matched to section 25 by TOKEN share, not byte share. Bytes per token
# differ by language under code32k -- Python 4.83, English 4.20, Hindi 8.44
# (section 25's own table) -- so equal byte shares would not be equal shares
# of the training the model actually receives, and tokens are the unit the
# 250,000-step budget is denominated in.
#
# The budgets below come from bytes/token measured on a 20 MB sample of each
# finished file with `bpe.py stats --tokenizer data/code32k.json`, not from
# section 25's table: the synthetic sources do not compress like raw GitHub.
#
#   tb_exercises 5.49   tb_opencode 4.62   tb_opc 4.47
#   gh_python    4.84   english     4.35   hindi  8.44
#
#                    section 25              here
#   Python           1,716M tok  60.3%       730M tok  61.1%
#   English            974M tok  34.2%       410M tok  34.3%
#   Hindi              157M tok   5.5%        55M tok   4.6%
#
# Hindi lands a point light because fetch_hindi.py streams one Wikipedia
# dump and 440 MB is what it yields; it is the smallest component and the
# one furthest from a Python benchmark, so it is the right place to absorb
# the shortfall.
#
# Within Python the ratio is inverted, which is the whole experiment:
# section 25 was 88% raw GitHub / 12% exercises, this is 11% raw GitHub /
# 89% textbook-quality synthetic.
#
# Total ~1,194M tokens against the 1,024M that 250,000 steps at batch 8 x 512
# consumes, so the run makes one pass and never wraps -- section 25 did not
# wrap at its own step 250,000 either, and a corpus small enough to repeat
# would have added a second difference between the two runs.
#
# The source names are tb_* rather than python/english/hindi on purpose.
# mix_corpus.py keeps every 50th document of a source as data/bench_<name>.txt
# and SKIPS that file if it already exists -- so reusing the old names would
# leave the previous held-out sets in place while their documents went into
# this training file. That is the contamination that invalidated the first
# long-context measurement (section 27). New names, new held-out sets.
python -u mix_corpus.py \
    --source tb_exercises data/tb_exercises.txt  950 \
    --source tb_opencode  data/tb_opencode.txt  1000 \
    --source tb_opc       data/tb_opc.txt       1000 \
    --source tb_github    data/gh_python.clean.txt     400 \
    --source tb_english   data/english_edu2.clean.txt 1700 \
    --source tb_hindi     data/hindi_tb.clean.txt      440 \
    --out data/textbook_mix.txt

echo "=== ENCODE ($(date +%H:%M)) ==="
# The coder's own tokenizer, unchanged, so bits/byte and pass@1 stay
# comparable with section 25.
[ -s data/textbook_mix.code32k.bin ] || python -u bpe.py encode \
    --tokenizer data/code32k.json --data data/textbook_mix.txt \
    --out data/textbook_mix.code32k.bin --workers 20 2>&1 | tr '\r' '\n' | tail -1

echo "=== BUILD DONE ($(date +%H:%M)) ==="
ls -la data/textbook_mix.txt data/textbook_mix.code32k.bin
