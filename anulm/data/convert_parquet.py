"""
Turn downloaded Hugging Face parquet / json files into this project's formats.

    python -m anulm convert_parquet fineweb   --in data/raw/HuggingFaceFW__fineweb-edu/sample/10BT/*.parquet --out data/english_edu.txt --mb 4000
    python -m anulm convert_parquet exercises --in data/raw/jinaai__code_exercises/data/*.parquet --out data/exercises.txt --jsonl data/sft_exercises.jsonl
    python -m anulm convert_parquet pairs     --in <parquet or json> --q-col question --a-col answer --jsonl data/sft_x.jsonl
    python -m anulm convert_parquet textbook  --in data/raw/OpenCoder-LLM__opc-sft-stage1/data/*.parquet --out data/textbook.txt --decontaminate
    python -m anulm convert_parquet clean     --in data/gh_python.txt --out data/gh_python.clean.txt

Text outputs use the corpus convention (title line, blank line, body, DOC_SEP
after, runs of 3+ newlines collapsed). Pair outputs are finetune.py's jsonl
(question, answer, title, lang). Parquet is streamed batch by batch, so a
2 GB shard never sits in memory as a table.
"""

from __future__ import annotations

import argparse
import glob
import json
import re
from pathlib import Path

from anulm.bpe import DOC_SEP

# 13 words is the window the Llama and phi papers use for decontamination, and
# it is short enough to catch a reworded benchmark problem while being long
# enough that ordinary Python does not collide by accident.
NGRAM = 13
_WORDS = re.compile(r"[a-z0-9_]+")

_BLANKS = re.compile(r"\n{3,}")
_FENCE = re.compile(r"```(?:python|py)?\n(.*?)```", re.DOTALL)


def clean(text: str) -> str:
    return _BLANKS.sub("\n\n", text.replace("\r\n", "\n").replace("\r", "\n")).strip()


def ngrams(text: str, stride: int = 1) -> set:
    """Hashes of every NGRAM-word window of `text` (lower-cased words).

    Documents are checked at stride 1. Checking every 4th window (as this once
    did, to save time) misses an overlap of 13-15 words: it yields only 1-3
    matching windows, and those can all fall between the checked positions."""
    w = _WORDS.findall(text.lower())
    return {hash(tuple(w[i:i + NGRAM])) for i in range(0, max(len(w) - NGRAM + 1, 0), stride)}


def benchmark_ngrams(root: Path) -> set:
    """Every 13-gram in MBPP and HumanEval -- prompts, solutions and tests.

    Synthetic instruction data is generated by models that have seen these
    benchmarks, so some of it *is* the benchmark. Training on that and then
    reporting pass@1 measures memorisation, which is the criticism phi-1
    attracted and the reason this filter exists rather than being assumed
    unnecessary.
    """
    import pyarrow.parquet as pq
    out, seen = set(), 0
    for pattern, cols in (
            ("google-research-datasets__mbpp/**/*.parquet", ("text", "code", "test_list")),
            ("openai__openai_humaneval/**/*.parquet", ("prompt", "canonical_solution", "test"))):
        for f in root.glob(pattern):
            for r in pq.read_table(str(f)).to_pylist():
                seen += 1
                for c in cols:
                    v = r.get(c)
                    if isinstance(v, list):
                        v = "\n".join(str(x) for x in v)
                    if v:
                        out |= ngrams(str(v))
    if not seen:
        # An empty set filters nothing and the run would still look clean.
        raise FileNotFoundError(f"no MBPP or HumanEval parquet under {root}; fetch them first "
                                "(python -m anulm fetch_hf) or drop --decontaminate")
    print(f"  decontamination: {seen} benchmark problems -> {len(out):,} 13-grams")
    return out


def rows(paths):
    """Yield dict rows from parquet files (streamed) or json/jsonl files."""
    import pyarrow.parquet as pq
    for pattern in paths:
        for path in sorted(glob.glob(pattern)) or [pattern]:
            if path.endswith(".parquet"):
                pf = pq.ParquetFile(path)
                for batch in pf.iter_batches(batch_size=2048):
                    yield from batch.to_pylist()
            elif path.endswith(".jsonl"):
                with open(path, encoding="utf-8") as f:
                    for line in f:
                        if line.strip():
                            yield json.loads(line)
            else:
                data = json.loads(Path(path).read_text(encoding="utf-8"))
                yield from (data if isinstance(data, list) else data.get("data", []))


def write_docs(out, docs, mb_cap: float | None):
    """Write docs to `out`, returns (count, MB); stops at mb_cap MB."""
    cap = (mb_cap or 1e12) * 1024 * 1024
    n, total = 0, 0
    with Path(out).open("w", encoding="utf-8", newline="\n") as f:
        for title, body in docs:
            body = clean(body)
            if not body:
                continue
            doc = f"{title.strip()}\n\n{body}{DOC_SEP}"
            f.write(doc)
            total += len(doc.encode("utf-8"))
            n += 1
            if n % 5000 == 0:
                print(f"\r  {n} docs, {total/1e6:.0f} MB", end="", flush=True)
            if total >= cap:
                break
    print(f"\r  {n} docs, {total/1e6:.0f} MB -> {out}")
    return n, total


def write_pairs(path, pairs):
    n = 0
    with Path(path).open("w", encoding="utf-8", newline="\n") as f:
        for it in pairs:
            f.write(json.dumps(it, ensure_ascii=False) + "\n")
            n += 1
    print(f"  {n} pairs -> {path}")
    return n


def textbook(args) -> None:
    """Instruction/output pairs as *pretraining* text, phi-1 style.

    phi-1 reached 50% HumanEval at 1.3B on 7B tokens of textbook-quality
    Python, where this project's coder reached 4.9% at 398M on a corpus that
    is 51% raw GitHub and 7% exercises (RESULTS.md 25). This writes the
    synthetic side as prose-plus-code documents so it can be the majority of
    a corpus rather than a garnish.
    """
    bench = benchmark_ngrams(Path(__file__).resolve().parents[2] / "data" / "raw") if args.decontaminate else set()
    kept = dropped = contaminated = failed = 0
    budget = (args.mb or 10_000) * 1_000_000
    written = 0
    with open(args.out, "w", encoding="utf-8", newline="\n") as fh:
        for r in rows(args.inputs):
            if args.score_col:
                # OpenCodeInstruct ships the result of running unit tests
                # against each solution, and 13% of rows fail all ten. A
                # corpus of confidently wrong Python is the opposite of the
                # thing being tested here, so --score-col average_test_score
                # --min-pair-score 1.0 keeps only solutions that passed.
                try:
                    if float(r.get(args.score_col) or 0) < args.min_pair_score:
                        failed += 1
                        continue
                except (TypeError, ValueError):
                    failed += 1
                    continue
            q = str(r.get(args.q_col) or r.get("instruction") or r.get("problem") or "")
            a = str(r.get(args.a_col) or r.get("output") or r.get("solution") or "")
            if not q or not a:
                dropped += 1
                continue
            if args.python_only:
                m = _FENCE.search(a)
                if not m and "def " not in a:
                    dropped += 1
                    continue
                if m:
                    a = m.group(1)
            doc = f"{clean(q)}\n\n{clean(a)}"
            if len(doc) < 80:
                dropped += 1
                continue
            if bench and (ngrams(doc) & bench):
                contaminated += 1
                continue
            fh.write(doc + DOC_SEP)
            # bytes, not characters: Devanagari is ~3 bytes per character in
            # UTF-8, so a character count would report a 456 MB Hindi corpus
            # as 181 MB and let --mb overshoot by the same factor.
            written += len((doc + DOC_SEP).encode("utf-8"))
            kept += 1
            if written >= budget:
                break
            if kept % 100_000 == 0:
                print(f"  {kept:,} kept, {contaminated:,} contaminated, "
                      f"{written/1e6:.0f} MB", flush=True)
    print(f"{args.out}: {kept:,} documents, {written/1e6:.1f} MB ({dropped:,} unusable, "
          f"{failed:,} below the test-score floor, {contaminated:,} dropped as benchmark overlap)")


def clean_corpus(args) -> None:
    """Drop benchmark-contaminated documents from an existing DOC_SEP corpus.

    The other modes filter while converting, which covers everything built
    from parquet. It does not cover a corpus that arrives as text --
    fetch_code.py's raw GitHub Python, fetch_hindi.py's Wikipedia -- and
    raw GitHub is exactly where a benchmark solution is most likely to be
    sitting, because MBPP and HumanEval problems are themselves public
    repositories. Measured on a 734 MB sample: 4 of MBPP's 257 problems and
    5 of HumanEval's 164 had their reference answer present.
    """
    from anulm.bpe import iter_documents
    bench = benchmark_ngrams(Path(__file__).resolve().parents[2] / "data" / "raw")
    kept = contaminated = 0
    written = 0
    with open(args.out, "w", encoding="utf-8", newline="\n") as fh:
        for doc in iter_documents(args.inputs[0]):
            if ngrams(doc) & bench:
                contaminated += 1
                continue
            fh.write(doc + DOC_SEP)
            written += len((doc + DOC_SEP).encode("utf-8"))
            kept += 1
    print(f"{args.out}: {kept:,} documents, {written/1e6:.1f} MB "
          f"({contaminated:,} dropped as benchmark overlap)")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("kind", choices=["fineweb", "exercises", "pairs", "textbook", "clean"])
    p.add_argument("--in", dest="inputs", nargs="+", required=True)
    p.add_argument("--out", help="text corpus output (fineweb, exercises)")
    p.add_argument("--jsonl", help="pair output (exercises, pairs)")
    p.add_argument("--mb", type=float, default=None, help="cap the text output at this many MB")
    p.add_argument("--q-col", default="question")
    p.add_argument("--a-col", default="answer")
    p.add_argument("--min-score", type=float, default=0.0, help="fineweb: keep rows with score >= this")
    p.add_argument("--max-answer-chars", type=int, default=2000)
    p.add_argument("--decontaminate", action="store_true",
                   help="drop any document sharing a 13-gram with MBPP or HumanEval")
    p.add_argument("--python-only", action="store_true",
                   help="pairs: keep only answers that contain a ```python block, and reduce the answer to it")
    p.add_argument("--score-col", default=None, help="pairs: numeric column to filter on (e.g. average_test_score)")
    p.add_argument("--min-pair-score", type=float, default=0.0)
    args = p.parse_args()

    if args.kind == "fineweb":
        def docs():
            for r in rows(args.inputs):
                if r.get("score", 99) < args.min_score:
                    continue
                text = r.get("text", "")
                if len(text) < 500:
                    continue
                yield r.get("url") or r.get("id") or "document", text
        write_docs(args.out, docs(), args.mb)

    elif args.kind == "exercises":
        # `problem` is the signature + docstring, `solution` the indented body
        # that continues it -- the same shape as a HumanEval prompt and its
        # completion. Joined with one newline they form the whole function.
        # A share of the set are fill-in-the-blank exercises whose "solution"
        # still has the blank ("# Complete the missing code ..."); those would
        # teach the model to leave gaps, so they are dropped.
        blank = re.compile(r"complete the (missing|code)|your code here|todo|\.\.\.\s*$|^\s*pass\s*$", re.I | re.M)
        items = []
        for r in rows(args.inputs):
            q, a = (r.get("problem") or "").rstrip(), (r.get("solution") or "").strip("\n").rstrip()
            if not q or not a or len(a) > args.max_answer_chars or not q.lstrip().startswith("def "):
                continue
            if blank.search(a) or "return" not in a:
                continue
            name = q.lstrip()[4:].split("(")[0].strip()
            items.append({"title": name, "question": q, "answer": a, "lang": "py"})
        if args.out:
            write_docs(args.out, (("# exercise: " + it["title"], it["question"] + "\n" + it["answer"]) for it in items), args.mb)
        if args.jsonl:
            write_pairs(args.jsonl, items)

    elif args.kind == "textbook":
        if not args.out:
            p.error("textbook writes a text corpus: pass --out")
        textbook(args)

    elif args.kind == "clean":
        if not args.out:
            p.error("clean writes a filtered corpus: pass --out")
        clean_corpus(args)

    else:  # pairs
        # Instruction pairs get the same benchmark filter as pretraining text
        # when asked. They are the more dangerous of the two: a contaminated
        # pretraining document is seen once in a trillion-token stream, and a
        # contaminated *tuning* pair is seen at the end, on the answer tokens
        # only, which is as close to training on the test set as this pipeline
        # gets.
        bench = benchmark_ngrams(Path(__file__).resolve().parents[2] / "data" / "raw") if args.decontaminate else set()
        stats = {"contaminated": 0}

        def pairs():
            for r in rows(args.inputs):
                if args.score_col:
                    try:
                        if float(r.get(args.score_col) or 0) < args.min_pair_score:
                            continue
                    except (TypeError, ValueError):
                        continue
                q, a = str(r.get(args.q_col) or "").strip(), str(r.get(args.a_col) or "").strip()
                if args.python_only:
                    m = _FENCE.search(a)
                    if not m:
                        continue
                    a = m.group(1).strip()
                if not q or not a or len(a) > args.max_answer_chars or len(q) > args.max_answer_chars:
                    continue
                if bench and (ngrams(q + "\n" + a) & bench):
                    stats["contaminated"] += 1
                    continue
                yield {"title": q.split("\n")[0][:60], "question": q, "answer": a, "lang": "py"}
        write_pairs(args.jsonl, pairs())
        if bench:
            print(f"  {stats['contaminated']:,} pairs dropped as benchmark overlap")


if __name__ == "__main__":
    main()
